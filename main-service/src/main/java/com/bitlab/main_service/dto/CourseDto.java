package com.bitlab.main_service.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Course, for example \"Java Developer\"")
public class CourseDto {

    @Schema(description = "Course id, generated by the server", accessMode = Schema.AccessMode.READ_ONLY, example = "1")
    private Long id;

    @NotBlank(message = "name must not be blank")
    @Size(max = 255, message = "name must be at most 255 characters")
    @Schema(description = "Course name", example = "Java Developer")
    private String name;

    @Schema(description = "Course description", example = "A beginner-friendly course about Java.")
    private String description;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime createdTime;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime updatedTime;
}