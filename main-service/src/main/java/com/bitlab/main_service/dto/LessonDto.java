package com.bitlab.main_service.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Lesson of a chapter, for example \"Lecture for if-else conditions\"")
public class LessonDto {

    @Schema(description = "Lesson id, generated by the server", accessMode = Schema.AccessMode.READ_ONLY, example = "1")
    private Long id;

    @NotBlank(message = "name must not be blank")
    @Size(max = 255, message = "name must be at most 255 characters")
    @Schema(description = "Lesson name", example = "Lecture for if-else conditions")
    private String name;

    @Schema(description = "Short description of the lesson")
    private String description;

    @Schema(description = "Lesson content (text or HTML)")
    private String content;

    @Min(value = 1, message = "order must be at least 1")
    @Schema(description = "Position of the lesson inside the chapter (used for sorting)", example = "1")
    private int order;

    @Schema(description = "Id of the chapter. Required when creating a lesson; it is not changed by an update.", example = "1")
    private Long chapterId;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime createdTime;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime updatedTime;
}