package com.bitlab.main_service.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Chapter of a course, for example \"if-else conditions\"")
public class ChapterDto {

    @Schema(description = "Chapter id, generated by the server", accessMode = Schema.AccessMode.READ_ONLY, example = "1")
    private Long id;

    @NotBlank(message = "name must not be blank")
    @Size(max = 255, message = "name must be at most 255 characters")
    @Schema(description = "Chapter name", example = "if-else conditions")
    private String name;

    @Schema(description = "Chapter description")
    private String description;

    @Min(value = 1, message = "order must be at least 1")
    @Schema(description = "Position of the chapter inside the course (used for sorting)", example = "2")
    private int order;

    @Schema(description = "Id of the course. Required when creating a chapter; it is not changed by an update.", example = "1")
    private Long courseId;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime createdTime;

    @Schema(accessMode = Schema.AccessMode.READ_ONLY)
    private LocalDateTime updatedTime;
}